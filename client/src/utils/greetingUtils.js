/**
 * Determine the current time-of-day slot.
 * @param {Date} [date=new Date()]
 * @returns {'morning' | 'afternoon' | 'evening' | 'night'}
 */
export function getTimeSlot(date = new Date()) {
  const hours = date.getHours();
  if (hours >= 4 && hours < 12) {
    return 'morning';
  }
  if (hours >= 12 && hours < 17) {
    return 'afternoon';
  }
  if (hours >= 17 && hours < 22) {
    return 'evening';
  }
  return 'night';
}

/**
 * Get time-based greeting formatted for the specified language.
 * @param {string} lang e.g. 'en', 'hi', 'pa', 'bn', etc.
 * @param {Date} [date=new Date()]
 * @returns {string} e.g. GOOD MORNING,, शुभ प्रभात,, শুভ অপরাহ্ন,, etc.
 */
export function getTimeGreeting(lang = 'en', date = new Date()) {
  const slot = getTimeSlot(date);
  const langKey = String(lang || 'en').toLowerCase().trim();
  const greetings = TIME_GREETINGS[langKey] || TIME_GREETINGS.en;
  return greetings[slot] || greetings.morning || 'GOOD MORNING,';
}

/**
 * Get full hero content (greeting, tagline, subtitle, cta) for the specified language and time.
 * @param {string} lang
 * @param {Date} [date=new Date()]
 * @returns {{ greeting: string, tagline: string, subtitle: string, cta: string }}
 */
export function getHeroContent(lang = 'en', date = new Date()) {
  const langKey = String(lang || 'en').toLowerCase().trim();
  const greeting = getTimeGreeting(langKey, date);
  const localized = HERO_LOCALIZATIONS[langKey] || HERO_LOCALIZATIONS.en;

  return {
    greeting,
    tagline: localized.tagline,
    subtitle: localized.subtitle,
    cta: localized.cta
  };
}
