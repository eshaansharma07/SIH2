/**
 * Helper to fetch localized string with fallback.
 * @param {string} lang e.g. 'ta', 'pa', 'hi', 'en'
 * @param {string} section e.g. 'nav', 'sidebar', 'cashflow', 'brand', 'dashboard'
 * @param {string} key e.g. 'inventory', 'todayLedger', etc.
 * @param {string} [fallback]
 * @returns {string}
 */
export function getSiteText(lang = 'en', section, key, fallback = '') {
  const langKey = String(lang || 'en').toLowerCase().trim();
  const dict = SITE_TRANSLATIONS[langKey] || SITE_TRANSLATIONS.en;
  if (dict && dict[section] && dict[section][key]) {
    return dict[section][key];
  }
  const enDict = SITE_TRANSLATIONS.en;
  if (enDict && enDict[section] && enDict[section][key]) {
    return enDict[section][key];
  }
  return fallback || key;
}
